def build_matrix():
    """由三张权威表展开为 18×18 完整矩阵"""
    matrix = {}
    for atk in TYPES:
        row = {}
        for dfn in TYPES:
            if dfn in NULL.get(atk, []):
                row[dfn] = 0
            elif dfn in SUPER.get(atk, []):
                row[dfn] = 2
            elif dfn in WEAK.get(atk, []):
                row[dfn] = 0.5
            else:
                row[dfn] = 1
        matrix[atk] = row
    return matrix


def main():
    matrix = build_matrix()
    payload = {
        "types": TYPES,
        "matrix": matrix,
        "rules": {"super": SUPER, "weak": WEAK, "null": NULL},
        "note": "18×18 完整克制矩阵；双属性防御方倍率 = 两个属性倍率相乘；攻击方按所选攻击属性计",
    }
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")
    # 打印矩阵便于人工核对
    header = "     " + "".join(f"{t:>4}" for t in TYPES)
    print(header)
    for atk in TYPES:
        row = " ".join(f"{matrix[atk][d]:>4}" for d in TYPES)
        print(f"{atk:>4} {row}")
    print(f"\n已生成 → {OUT}")


if __name__ == "__main__":
    main()
