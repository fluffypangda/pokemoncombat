def rate(atk, dfn):
    """单属性攻击倍率"""
    return M[atk][dfn]


def rate2(atk, def_types):
    """双属性防御方倍率 = 两属性倍率相乘"""
    r = 1.0
    for t in def_types:
        r *= rate(atk, t)
    return r


