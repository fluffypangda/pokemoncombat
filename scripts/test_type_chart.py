def main():
    failed = 0
    for atk, dfns, expected, desc in CASES:
        if len(dfns) == 1:
            got = rate(atk, dfns[0])
        else:
            got = rate2(atk, dfns)
        ok = abs(got - expected) < 1e-9
        mark = "PASS" if ok else "FAIL"
        if not ok:
            failed += 1
        print(f"[{mark}] {desc}: 期望 {expected} 实得 {got}")
    # 结构校验：18 属性全覆盖、矩阵 18×18、倍率 ∈ {0,0.5,1,2}
    tset = set(TYPES)
    assert len(tset) == 18, "属性数应为18"
    assert set(M.keys()) == tset, "矩阵攻击方属性缺失"
    for atk in TYPES:
        assert set(M[atk].keys()) == tset, f"矩阵 {atk} 防御方属性缺失"
        for dfn in TYPES:
            assert M[atk][dfn] in (0, 0.5, 1, 2), f"{atk}→{dfn} 非法倍率 {M[atk][dfn]}"
    print(f"\n结构校验: 18×18 矩阵完整，倍率值域合法")
    print(f"单测: {len(CASES)} 条，失败 {failed} 条")
    if failed:
        raise SystemExit(1)
    print("全部通过 ✓")


if __name__ == "__main__":
    main()
